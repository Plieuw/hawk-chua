#!/usr/bin/env python3
"""The knob cells' 40 x 40 tile (ui.c ui_knob): per pixel its place on the 270-degree sweep and how much of each
ring covers it (anti-aliased by 4 x 4 supersampling): the value's outer ring, the modulation's inner ring; the
knob itself see-through, only its pointer drawn. Writes firmware/src/knob_tables.h."""
import math
N = 40
C = (N - 1) / 2.0
R_TR0, R_TR1 = 16.4, 19.6          # the value's ring (outer)
R_MO0, R_MO1 = 12.2, 14.6          # the modulation's ring (inner)
SS = 4

def cover(r0, r1, x, y):
    n = 0
    for i in range(SS):
        for j in range(SS):
            px = x + (i + 0.5) / SS - 0.5 - C
            py = y + (j + 0.5) / SS - 0.5 - C
            d = math.hypot(px, py)
            n += r0 <= d < r1
    return n * 255 // (SS * SS)

ang, track, ring = [], [], []
for y in range(N):
    for x in range(N):
        dx, dy = x - C, y - C
        # clockwise from straight down; the sweep from 45 to 315 degrees (the gap at the bottom)
        t = math.degrees(math.atan2(-dx, dy)) % 360.0
        u = (t - 45.0) / 270.0
        ang.append(255 if u < 0 or u > 1 else min(254, int(u * 254 + 0.5)))
        track.append(cover(R_TR0, R_TR1, x, y))
        ring.append(cover(R_MO0, R_MO1, x, y))

def arr(name, a):
    s = "static const uint8_t %s[%d] = {\n" % (name, len(a))
    for i in range(0, len(a), 20):
        s += "    " + ", ".join(str(v) for v in a[i:i + 20]) + ",\n"
    return s + "};\n"

out = "/* generated by tools/gen_knob_tables.py: the knob cells' tile (ui.c ui_knob) */\n#pragma once\n#include <stdint.h>\n"
out += "#define KN_W %d\n" % N
# the pointer for a value 0..127: its ends, Q4 (from 2 to 10 px out of the middle)
pt = []
for v in range(128):
    t = math.radians(45 + 270 * v / 127)
    dx, dy = -math.sin(t), math.cos(t)
    for r in (2.0, 10.0):
        pt += [int(round((C + dx * r) * 16)), int(round((C + dy * r) * 16))]
s16 = "static const int16_t KN_PTR[128][4] = {\n"
for v in range(128):
    s16 += "    {%d, %d, %d, %d},\n" % tuple(pt[v * 4:v * 4 + 4])
s16 += "};\n"
out += s16
out += arr("KN_ANG", ang) + arr("KN_TRACK", track) + arr("KN_RING", ring)
open("firmware/src/knob_tables.h", "w").write(out)
print("ok", len(ang))
