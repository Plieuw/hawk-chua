#!/usr/bin/env python3
"""The knob cells' 40 x 40 tile (ui.c ui_knob): per pixel its place on the 270-degree sweep and how much of each
layer covers it (anti-aliased by 4 x 4 supersampling): the knob's body (with its shade, lit from the upper left),
the value's track, the modulation's outer ring. Writes firmware/src/knob_tables.h."""
import math
N = 40
C = (N - 1) / 2.0
R_BODY = 12.6
R_TR0, R_TR1 = 14.6, 17.0          # the value's track
R_MO0, R_MO1 = 18.3, 19.8          # the modulation's ring
SS = 4

def cover(r0, r1, x, y):
    n = 0
    for i in range(SS):
        for j in range(SS):
            px = x + (i + 0.5) / SS - 0.5 - C
            py = y + (j + 0.5) / SS - 0.5 - C
            d = math.hypot(px, py)
            n += r0 <= d < r1
    return n * 255 // (SS * SS)

ang, body, shade, track, ring = [], [], [], [], []
for y in range(N):
    for x in range(N):
        dx, dy = x - C, y - C
        # clockwise from straight down; the sweep from 45 to 315 degrees (the gap at the bottom)
        t = math.degrees(math.atan2(-dx, dy)) % 360.0
        u = (t - 45.0) / 270.0
        ang.append(255 if u < 0 or u > 1 else min(254, int(u * 254 + 0.5)))
        body.append(cover(0, R_BODY, x, y))
        # the body's light: brighter towards the upper left, a darker rim
        d = math.hypot(dx, dy)
        l = 0.55 + 0.35 * max(-1.0, min(1.0, (-dx - dy) / (R_BODY * 1.2))) - 0.25 * max(0.0, d - R_BODY + 2.5) / 2.5
        shade.append(max(0, min(255, int(l * 255))))
        track.append(cover(R_TR0, R_TR1, x, y))
        ring.append(cover(R_MO0, R_MO1, x, y))

def arr(name, a):
    s = "static const uint8_t %s[%d] = {\n" % (name, len(a))
    for i in range(0, len(a), 20):
        s += "    " + ", ".join(str(v) for v in a[i:i + 20]) + ",\n"
    return s + "};\n"

out = "/* generated by tools/gen_knob_tables.py: the knob cells' tile (ui.c ui_knob) */\n#pragma once\n#include <stdint.h>\n"
out += "#define KN_W %d\n" % N
# the pointer for a value 0..127: its ends, Q4 (from 3.5 to 11 px out of the middle)
pt = []
for v in range(128):
    t = math.radians(45 + 270 * v / 127)
    dx, dy = -math.sin(t), math.cos(t)
    for r in (3.5, 11.0):
        pt += [int(round((C + dx * r) * 16)), int(round((C + dy * r) * 16))]
s16 = "static const int16_t KN_PTR[128][4] = {\n"
for v in range(128):
    s16 += "    {%d, %d, %d, %d},\n" % tuple(pt[v * 4:v * 4 + 4])
s16 += "};\n"
out += s16
out += arr("KN_ANG", ang) + arr("KN_BODY", body) + arr("KN_SHADE", shade) + arr("KN_TRACK", track) + arr("KN_RING", ring)
open("firmware/src/knob_tables.h", "w").write(out)
print("ok", len(ang))
