"""HAWK CHUA on FM1 Open: the UI's two text faces as 4-bit alpha bitmaps (open/app/hc_gfx.c draws them).

  gen_font.py OUT.h [FONT.ttf]

Inter Tight (SIL OFL 1.1, assets/fonts) at 12 px weight 400 (AF_S) and 15 px weight 500 (AF_M): ASCII 32..126 and the
ellipsis (code 0x85). Each glyph is cropped to its ink; advances in 1/16 px. The line box: AF_S 15 px with the
baseline at 12, AF_M 19 px with it at 15; AF_x_CAP_Y / AF_x_CAP_H: the rows the ink of H covers."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FACES = [("AF_S", 12, 400, 15, 12), ("AF_M", 15, 500, 19, 15)]   # name, px, weight, line height, baseline
CHARS = [chr(c) for c in range(32, 127)] + ["…"]             # the ellipsis: code 0x85


def face(path, px, wght):
    f = ImageFont.truetype(str(path), px)
    try:
        f.set_variation_by_axes([wght])
    except Exception:
        pass
    return f


def glyph(f, ch, asc, h):
    """(bitmap rows as 0..15, bx, by, bw, bh, advance in 1/16 px); by from the line top"""
    pad = 8
    img = Image.new("L", (h * 3 + pad * 2, h + pad * 2), 0)
    ImageDraw.Draw(img).text((pad, pad + asc), ch, font=f, fill=255, anchor="ls")
    adv = round(f.getlength(ch) * 16)
    box = img.getbbox()
    if not box or ch == " ":
        return [], 0, 0, 0, 0, adv
    x0, y0, x1, y1 = box
    rows = [[(img.getpixel((x, y)) * 15 + 127) // 255 for x in range(x0, x1)] for y in range(y0, y1)]
    return rows, x0 - pad, y0 - pad, x1 - x0, y1 - y0, adv


def main():
    out = Path(sys.argv[1])
    ttf = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "assets" / "fonts" / "InterTight[wght].ttf"
    o = ["/* generated by open/tools/gen_font.py: Inter Tight (SIL OFL 1.1), 4-bit alpha, two pixels a byte (the left"
         " in the low nibble) */", "#pragma once", ""]
    for name, px, wght, h, asc in FACES:
        f = face(ttf, px, wght)
        data, gl = bytearray(), []
        for ch in CHARS:
            rows, bx, by, bw, bh, adv = glyph(f, ch, asc, h)
            off = len(data)
            for r in rows:
                r = r + [0] * (len(r) & 1)
                for i in range(0, len(r), 2):
                    data.append(r[i] | r[i + 1] << 4)
            gl.append((off, adv, bx, by, bw, bh))
        _, _, hy, _, hh, _ = glyph(f, "H", asc, h)
        o.append(f"static const hc_glyph_t {name}_G[{len(gl)}] = {{")
        o += ["    " + " ".join("{%d, %d, %d, %d, %d, %d}," % g for g in gl[i:i + 6]) for i in range(0, len(gl), 6)]
        o.append("};")
        o.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
        o += ["    " + "".join("%d," % b for b in data[i:i + 32]) for i in range(0, len(data), 32)]
        o.append("};")
        o.append(f"static const aafont_t {name} = {{{h}, {asc}, 32, 126, {name}_G, {name}_DATA}};")
        o.append(f"#define {name}_CAP_Y {hy}   /* the ink of H: rows {hy} .. {hy + hh - 1} of the line */")
        o.append(f"#define {name}_CAP_H {hh}")
        o.append("")
    out.write_text("\n".join(o))


if __name__ == "__main__":
    main()
